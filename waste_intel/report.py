"""Markdown report of one detection cycle (Greek, for the municipality's energy team)."""

from __future__ import annotations

from collections import Counter

from .detect import WASTE_TYPES

TYPE_GR = {
    "ghost_load": "Φορτίο νύχτας (ghost load)",
    "unoccupied_waste": "Κατανάλωση σε κλειστό κτήριο",
    "hvac_unoccupied": "Θέρμανση/ψύξη σε κλειστό κτήριο",
    "equipment_fault": "Υπερκατανάλωση σε ώρες λειτουργίας (πιθανή βλάβη)",
    "post_holiday_spike": "Αιχμή μετά από αργίες",
    "degradation_drift": "Σταδιακή αύξηση (φθορά εξοπλισμού)",
    "meter_quality": "Ποιότητα δεδομένων μετρητή",
}
STATUS_GR = {"anomalous": "ανωμαλία", "watch": "παρακολούθηση", "normal": "κανονικό", "data_issue": "πρόβλημα δεδομένων"}
TREND_GR = {"improving": "βελτιώνεται", "stable": "σταθερό", "deteriorating": "χειροτερεύει"}
SOURCE_GR = {"sensor": "αισθητήρας σχολείου", "eunice": "EUNICE", "dei": "τηλεμετρία ΔΕΗ"}


def _n(x, d=0):
    if x is None:
        return "–"
    return f"{x:,.{d}f}".replace(",", "X").replace(".", ",").replace("X", ".")


def _pct(x):
    return "–" if x is None else f"{x * 100:.0f}%"


def build_report(config, entities, results, register, evaluation) -> str:
    L = []
    a = L.append
    th = config["thresholds"]
    a("# Service 2: Ανίχνευση ανωμαλιών και σπατάλης ενέργειας")
    a("")
    a(f"Run `{config['run_id']}` · {config['model_version']} · ημερομηνία {config['run_date']} · "
      f"διάρκεια {config['elapsed_s']} s")
    a("")
    a("Δεδομένα έως: " + ", ".join(f"{SOURCE_GR.get(k, k)} {v}" for k, v in config["data_end"].items()) + ".")
    a("")

    # coverage
    a("## 1. Ποιοι μετρητές αναλύθηκαν")
    a("")
    a("| Πηγή | Υποψήφιοι | Αναλύθηκαν | Εκτός |")
    a("|---|---:|---:|---:|")
    for s in ("sensor", "eunice", "dei"):
        es = [e for e in entities if e["source"] == s]
        if es:
            k = sum(e["qc"]["ok"] for e in es)
            a(f"| {SOURCE_GR[s]} | {len(es)} | {k} | {len(es) - k} |")
    reasons = Counter()
    for e in entities:
        if not e["qc"]["ok"]:
            first = e["qc"]["reasons"][0] if e["qc"]["reasons"] else "άγνωστο"
            key = first.split(" (")[0]
            for pat in ("κάλυψη", "μηδενικά", "ακραίες", "κολλημένη", "αρνητικές", "kWh/ημέρα", "χωρίς δεδομένα", "ίδια σειρά"):
                if pat in first:
                    key = pat
                    break
            reasons[key] += 1
    a("")
    a(f"Κριτήρια (τελευταίες {th['qc_window_days']} ημέρες): δεδομένα μέσα στις τελευταίες {th['qc_max_age_days']} ημέρες, "
      f"κάλυψη ≥ {th['qc_min_coverage']:.0%}, μηδενικά ≤ {th['qc_max_zero_share']:.0%}, απομονωμένες αιχμές ≤ "
      f"{th['qc_max_spike_share']:.1%}, κολλημένη τιμή ≤ {th['qc_max_stuck_share']:.0%}, καμία αρνητική τιμή, "
      f"≥ {th['qc_min_kwh_day']:g} kWh/ημέρα, σχολείο ≤ {th['qc_max_kwh_day_school']:,.0f} kWh/ημέρα, όχι διπλή σειρά.")
    a("")
    a("Πρώτος λόγος αποκλεισμού: " + ", ".join(f"{k} {v}" for k, v in reasons.most_common()) + ". "
      "Η πλήρης λίστα με τις τιμές κάθε μετρητή είναι στο `quality.json`.")
    a("")

    # register
    a("## 2. Μητρώο σπατάλης")
    a("")
    total = sum(r["annual_eur"] for r in register)
    live = sum(r["annual_eur"] for r in register if not r["historical"])
    a(f"{len(register)} γραμμές, εκτιμώμενο ετήσιο κόστος {_n(total)} € "
      f"(από αυτά {_n(live)} € σε μετρητές με τρέχοντα δεδομένα). Η ετήσια τιμή προκύπτει από τον ρυθμό της "
      f"σπατάλης στις τελευταίες {th['monitor_days']} ημέρες προβεβλημένο σε 12 μήνες, άρα είναι τάξη μεγέθους, "
      "όχι μέτρηση.")
    a("")
    a("| # | Κτήριο | Πηγή | Τύπος | Περιστατικά | Παρατηρ. kWh | kWh/έτος | €/έτος | Αξιοπιστία |")
    a("|---:|---|---|---|---:|---:|---:|---:|---:|")
    for i, r in enumerate(register[:25], 1):
        src = SOURCE_GR[r["source"]] + (" (ιστορικά)" if r["historical"] else "")
        a(f"| {i} | {r['name']} | {src} | {TYPE_GR[r['type']]} | {r['events']} | {_n(r['observed_excess_kwh'])} | "
          f"{_n(r['annual_kwh'])} | {_n(r['annual_eur'])} | {r['confidence']:.2f} |")
    if len(register) > 25:
        a(f"| | … και {len(register) - 25} ακόμη στο `register.json` | | | | | | | |")
    a("")
    by_type = Counter()
    eur_type = Counter()
    for r in register:
        by_type[r["type"]] += 1
        eur_type[r["type"]] += r["annual_eur"]
    a("Ανά τύπο: " + "; ".join(f"{TYPE_GR[t]}: {by_type[t]} μετρητές, {_n(eur_type[t])} €/έτος"
                              for t in WASTE_TYPES if by_type[t]) + ".")
    a("")

    # status
    a("## 3. Κατάσταση ανά μετρητή")
    a("")
    st = Counter(r["status"] for r in results)
    tr = Counter(r["trend"] for r in results)
    a("Κατάσταση: " + ", ".join(f"{STATUS_GR[k]} {v}" for k, v in st.most_common()) + ". "
      "Τάση (τελευταίες 28 ημέρες έναντι των 28 προηγούμενων): " + ", ".join(f"{TREND_GR[k]} {v}" for k, v in tr.most_common()) + ".")
    a("")
    dq = Counter(d.get("subtype") for r in results for d in r["detections"] if d["type"] == "meter_quality")
    if dq:
        a("Ευρήματα ποιότητας δεδομένων στις τελευταίες 28 ημέρες (δεν μετράνε ως σπατάλη): " +
          ", ".join(f"{k} {v}" for k, v in dq.most_common()) + ".")
        a("")

    # evaluation
    a("## 4. Αξιολόγηση")
    a("")
    a("### 4.1 Ακρίβεια βάσης αναφοράς (walk-forward, τελευταίες 28 ημέρες)")
    a("")
    a("Κάθε ημέρα προβλέπεται μόνο από προηγούμενες ημέρες. Αναφορά: η ίδια ώρα μία εβδομάδα πριν. "
      "Το RMSE δίνεται ως ποσοστό της μέσης ημερήσιας κατανάλωσης κάθε μετρητή (διάμεσος), για να συγκρίνονται μικρά και μεγάλα κτήρια.")
    a("")
    a("| Πηγή | Μετρητές | Καλύτερη από αναφορά | Ημερήσιο RMSE (βάση) | Ημερήσιο RMSE (αναφορά) |")
    a("|---|---:|---:|---:|---:|")
    for s, v in evaluation["baseline"].items():
        a(f"| {SOURCE_GR[s]} | {v['meters']} | {v['better_than_reference']} | {_pct(v['median_daily_rmse_share'])} | "
          f"{_pct(v['median_daily_rmse_share_reference'])} |")
    a("")
    a("MAE και RMSE ανά μετρητή (ανά 15λεπτο και ανά ημέρα, σε kWh) είναι στο `buildings.json`.")
    a("")
    syn = evaluation.get("synthetic")
    if syn:
        a("### 4.2 Ανίχνευση σε τεχνητά περιστατικά")
        a("")
        a("Δεν υπάρχει ακόμη μητρώο επιβεβαιωμένων περιστατικών (επισκέψεις συντήρησης, αναφορές). Για να μετρηθεί ο "
          "ανιχνευτής, προστέθηκαν γνωστά περιστατικά σε αντίγραφο των πραγματικών δεδομένων κάθε μετρητή και ο ανιχνευτής "
          "έτρεξε walk-forward. **Τα νούμερα αυτά μετρούν τον ανιχνευτή σε ελεγχόμενες συνθήκες, όχι σε επιβεβαιωμένα "
          "πραγματικά περιστατικά.**")
        a("")
        a("| Περιστατικό | Δοκιμές | Recall (σωστός τύπος) | Recall (οποιοσδήποτε τύπος) | Precision | Χρόνος εντοπισμού (διάμεσος, ώρες) | MAPE εκτίμησης kWh |")
        a("|---|---:|---:|---:|---:|---:|---:|")
        names = {"ghost_load": "+50% φορτίο νύχτας, 10 νύχτες", "unoccupied_waste": "φορτίο σε 4 μέρες Σαββατοκύριακου",
                 "equipment_fault": "+30% στις ώρες λειτουργίας, 3 μέρες", "degradation_drift": "σταδιακά έως +15% σε 35 μέρες"}
        for k, v in syn.items():
            if k == "clean":
                continue
            a(f"| {names.get(k, k)} | {v['injected']} | {_pct(v['recall'])} | {_pct(v['recall_any_type'])} | "
              f"{_pct(v['precision'])} | {_n(v['median_hours_to_detection'], 1)} | {_pct(v['waste_mape'])} |")
        if "clean" in syn:
            c = syn["clean"]
            a("")
            a(f"Χωρίς τεχνητό περιστατικό: {c['flags']} ειδοποιήσεις σε {c['meters']} μετρητές × 38 ημέρες "
              f"({_n(c['flags_per_meter_week'], 2)} ανά μετρητή και εβδομάδα). Μέρος τους μπορεί να είναι πραγματική "
              "σπατάλη, οπότε αυτός είναι ανώτατος δείκτης ψευδών ειδοποιήσεων.")
        a("")
        a("Precision: από τις ειδοποιήσεις που δημιούργησε η προσθήκη (όσες υπάρχουν ήδη στο ανέγγιχτο αντίγραφο "
          "εξαιρούνται, γιατί δεν ξέρουμε αν είναι σωστές), το ποσοστό που πέφτει πάνω στο τεχνητό περιστατικό. "
          "Χρόνος εντοπισμού: από την αρχή του περιστατικού ως τη στιγμή που επιβεβαιώνεται (3η νύχτα για φορτίο νύχτας, "
          "3η ώρα για περιστατικά ωρών, η ημέρα του κύκλου για σταδιακή αύξηση). MAPE: η επιπλέον ενέργεια που μέτρησε ο "
          "ανιχνευτής στις ημέρες του περιστατικού σε σχέση με την ενέργεια που προστέθηκε.")
        a("")

    # method and limits
    a("## 5. Μέθοδος")
    a("")
    a(f"- **Βάση αναφοράς:** για κάθε ημέρα, οι {th['baseline_neighbours']} πιο όμοιες προηγούμενες ημέρες του ίδιου "
      f"τύπου (εργάσιμη, Σάββατο, Κυριακή/αργία, διακοπές σχολείων) έως {th['baseline_lookback_days']} ημέρες πίσω, "
      "με τις πιο κοντινές βαθμοημέρες θέρμανσης (18 °C) και ψύξης (22 °C). Διάμεσος και robust διασπορά ανά 15λεπτο. "
      "Ημέρες με ανίχνευση δεν μπαίνουν στις επόμενες βάσεις.")
    a(f"- **Ανίχνευση ανά 15λεπτο:** υπέρβαση > {th['z_threshold']:g}σ και > {th['min_excess_share']:.0%} του αναμενόμενου "
      f"και > {th['min_excess_kwh']} kWh. Περιστατικό: ≥ {th['event_min_slots'] // 4} ώρες συνεχόμενα, ή ≥ "
      f"{th['ghost_min_nights']} νύχτες για φορτίο νύχτας.")
    a("- **Αξιοπιστία (0–1):** ένταση της απόκλισης (35%), διάρκεια (25%), συνέπεια μέσα στο περιστατικό (20%), "
      f"ποιότητα δεδομένων και βάσης (20%). Στο μητρώο μπαίνουν όσα έχουν ≥ {th['confidence_min']}.")
    a("- **Κόστος:** μέση τιμή €/kWh κάθε κτηρίου από τους λογαριασμούς "
      f"{th['price_years'][0]}–{th['price_years'][1]} (χωρίς δημοτικά τέλη), αλλιώς ο διάμεσος του Δήμου "
      f"({_n(config['fallback_price_eur_kwh'], 3)} €/kWh).")
    a("- **Φωτοβολταϊκά:** στο κτήριο με inverter η κατανάλωση είναι ρεύμα από το δίκτυο + παραγωγή inverter.")
    a("- **Ωράριο:** σχολεία 08:00–16:00, άλλα κτήρια 07:00–17:00, νύχτα 00:00–06:00. Αργίες και σχολικές διακοπές "
      "κατά προσέγγιση (Χριστούγεννα 24/12–7/1, Πάσχα Μ. Δευτέρα–Κυριακή Θωμά, καλοκαίρι 21/6–10/9, 30/1, 17/11).")
    a("")
    a("## 6. Τι λείπει σε σχέση με την προδιαγραφή")
    a("")
    a("- **Επιβεβαιωμένα περιστατικά:** precision, recall και MAPE σε πραγματικά περιστατικά χρειάζονται μητρώο "
      "επιβεβαιώσεων από συντήρηση ή διαχειριστές. Μέχρι τότε ισχύει μόνο το τεχνητό τεστ.")
    a("- **Ασυμφωνίες με λογαριασμούς:** οι λογαριασμοί (έως 2024) και η τηλεμετρία δεν έχουν κοινές περιόδους.")
    a("- **Σταδιακή αύξηση:** χρειάζεται σύγκριση με ημέρες παρόμοιου καιρού τουλάχιστον 8 εβδομάδες πριν. Με ~3 μήνες "
      "ιστορικό και μετάβαση από καλοκαίρι σε φθινόπωρο τέτοιες ημέρες δεν υπάρχουν, οπότε ο έλεγχος αυτός σήμερα "
      "σπάνια αποφαίνεται (recall σωστού τύπου στο τεχνητό τεστ ≈ 0). Είναι σκόπιμα αυστηρός: σε πρώτη εκδοχή χωρίς "
      "αυτόν τον έλεγχο, η εποχική ψύξη ενός κτηρίου τον Μάιο εμφανιζόταν ως φθορά.")
    a("- **Ρύθμιση ορίων:** τα όρια ρυθμίστηκαν σε 4 γύρους πάνω στα ίδια τεχνητά τεστ (λιγότερες ψευδείς "
      "ειδοποιήσεις, έλεγχος ανά ζώνη ωρών, έλεγχος καιρού). Τα αποτελέσματα της ενότητας 4.2 είναι επομένως "
      "αισιόδοξα· η πραγματική εικόνα θα φανεί όταν υπάρξουν επιβεβαιωμένα περιστατικά.")
    a("- **Ήπιες βλάβες:** υπερκατανάλωση +30% στις ώρες λειτουργίας εντοπίζεται σε περίπου 1 στις 4–5 περιπτώσεις· "
      "ο ανιχνευτής πιάνει αξιόπιστα μεγαλύτερες αποκλίσεις και φορτία νύχτας / κλειστού κτηρίου.")
    a("- **Ιστορικό:** οι αισθητήρες σχολείων έχουν συνήθως ~3 μήνες, όχι 12. Η περίοδος θέρμανσης ξεκινά τώρα, οπότε "
      "η διόρθωση για τον καιρό θα βελτιωθεί όσο μαζεύονται χειμωνιάτικες ημέρες.")
    a("- **Καιρός:** μόνο ημερήσιος (μέση θερμοκρασία, βαθμοημέρες), όχι ωριαίος.")
    a("- **Θερμοστάτες:** ο τύπος «θέρμανση/ψύξη σε κλειστό κτήριο» βγαίνει μόνο όπου υπάρχει θερμοστάτης στο ίδιο σχολείο.")
    a("- **Τηλεμετρία ΔΕΗ:** σταματά στις 31/5/2026, άρα αναλύεται ως ιστορικό, όχι σε πραγματικό χρόνο.")
    a("- **EUNICE:** 28 από τους 30 μετρητές δεν έχουν αντιστοίχιση με κτήριο και εμφανίζονται με τον κωδικό τους.")
    a("")
    a("## 7. Αρχεία")
    a("")
    a("`config.json` (όρια, έκδοση), `quality.json`, `buildings.json` (ανά μετρητή: κατάσταση, τάση, ευρήματα με "
      "στοιχεία, ακρίβεια), `register.json`, `evaluation.json`, `report.md`. Όλα στον φάκελο του run, ώστε κάθε "
      "εύρημα να αναπαράγεται με τα όρια και την έκδοση που το έβγαλαν.")
    return "\n".join(L) + "\n"
